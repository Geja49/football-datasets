def normaliser_url(url):
    texte = (url or "").strip()
    if not texte:
        return ""
    if texte.startswith("www."):
        texte = "https://" + texte
    if texte.startswith("http://"):
        texte = "https://" + texte[len("http://") :]
    if not texte.startswith("https://"):
        return ""
    return texte.split()[0].rstrip("/")
